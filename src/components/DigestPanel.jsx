import PropTypes from 'prop-types';

/**
 * The digest: the sections the visible feed leans on, each fronted by the story
 * that best represents it.
 *
 * With no summariser endpoint configured this is produced locally and
 * deterministically — see `src/ai/localSummarizer.js`.
 */
export default function DigestPanel({ digest }) {
  if (!digest || digest.bullets.length === 0) return null;

  const providerNote =
    digest.provider === 'local'
      ? 'Generated locally — no API key, no network call'
      : 'Generated by the configured digest service';

  return (
    <section className="digest" aria-labelledby="digest-title">
      <div className="digest__head">
        <h2 className="digest__title" id="digest-title">
          Where the feed is weighted
        </h2>
        <span className="digest__note">
          {digest.articleCount} articles · {providerNote}
        </span>
      </div>
      <ul className="digest__list">
        {digest.bullets.map((bullet) => (
          <li className="digest__item" key={bullet.term}>
            <span className="digest__term">
              {bullet.term} · {bullet.count} {bullet.count === 1 ? 'story' : 'stories'}
            </span>
            <p className="digest__headline">{bullet.headline}</p>
            <span className="digest__source">{bullet.sourceLabel}</span>
          </li>
        ))}
      </ul>
    </section>
  );
}

DigestPanel.propTypes = {
  digest: PropTypes.shape({
    provider: PropTypes.string,
    articleCount: PropTypes.number,
    bullets: PropTypes.arrayOf(
      PropTypes.shape({
        term: PropTypes.string,
        count: PropTypes.number,
        headline: PropTypes.string,
        sourceLabel: PropTypes.string,
      })
    ),
  }),
};

DigestPanel.defaultProps = { digest: null };
