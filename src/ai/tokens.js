/** Shortest token we treat as meaningful. Below this it is almost always noise. */
export const MIN_TOKEN_LENGTH = 4;

export function tokenize(text) {
  return String(text)
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((token) => token.length >= MIN_TOKEN_LENGTH && !STOPWORDS.has(token));
}

/** Split on sentence-final punctuation, keeping the punctuation off the result. */
export function splitSentences(text) {
  return String(text)
    .split(/(?<=[.!?])\s+/)
    .map((sentence) => sentence.trim())
    .filter(Boolean);
}
